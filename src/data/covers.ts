/**
 * Black tap-to-reveal covers over evidence photos, per screen id.
 * Each rectangle is [left, top, right, bottom] in pixels on the 1366×768 screen.
 */
export interface Cover {
  x: number;
  y: number;
  w: number;
  h: number;
  /** Number shown on the cover; defaults to its position (1, 2, 3…). */
  label?: string;
}

const W = 1366;
const H = 768;

type Px = [number, number, number, number];

function rects(list: Px[], labels?: string[]): Cover[] {
  return list.map(([l, t, r, b], i) => ({ x: l / W, y: t / H, w: (r - l) / W, h: (b - t) / H, label: labels?.[i] }));
}

/** Builds covers for a regular photo grid from column [left, right] and row [top, bottom] edges. */
function grid(cols: [number, number][], rows: [number, number][]): Cover[] {
  return rects(rows.flatMap(([t, b]) => cols.map(([l, r]) => [l, t, r, b] as Px)));
}

